from __future__ import annotations

import os

SUPPORTED_LANGUAGES = ("de", "en", "fr", "it", "es")
DEFAULT_LANGUAGE = "en"


def _detect_language() -> str:
    """Language code from the session environment (LC_ALL > LC_MESSAGES >
    LANG, the same precedence gettext uses), so the app follows GNOME's own
    Language setting without any in-app switcher. Evaluated once at import
    time -- a plain module-level constant is all this needs."""
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var)
        if value:
            code = value[:2].lower()
            return code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    return DEFAULT_LANGUAGE


